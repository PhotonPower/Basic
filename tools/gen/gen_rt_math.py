#!/usr/bin/env python3
"""Generates runtime/m68k/rt_math.s, the MC68000 port of runtime/ref/rt_math.c.

The functions are long sequences of calls of the basic operations (fp_add, fp_mul ...); this script
writes them from a short description, step by step in the order of the C code, so that the port
performs exactly the same operations with the same constants (docs/numerics.md). The constants are
read from the C file. Run after a change of rt_math.c:

    python3 tools/gen/gen_rt_math.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
C = (ROOT / "runtime/ref/rt_math.c").read_text()

consts = dict(re.findall(r"#define (C_\w+) \(\(f64\)(0x[0-9A-F]+)u\)", C))
tables = {name: re.findall(r"0x[0-9A-F]+u", body)
          for name, body in re.findall(r"static const f64 rt_math__(\w+)\[\d+\] = \{(.*?)\};", C, re.S)}

out = []


def emit(s=""):
    out.append(s)


def ins(s):
    out.append("        " + s)


def label(name):
    return "rt_math__" + name if not name.startswith(".") else name


def opnd(x, off):
    """operand: frame slot ('s3'), constant ('C_HALF') or table entry"""
    if x.startswith("s"):
        return f"{-8 * int(x[1:]) + off}(A6)"
    return f"rt_math__{x.lower()}+{off}" if off else f"rt_math__{x.lower()}"


def ld(x, r=0):
    ins(f"MOVE.L  {opnd(x, 0)},D{r}")
    ins(f"MOVE.L  {opnd(x, 4)},D{r + 1}")


def st(dst):
    ins(f"MOVE.L  D0,{opnd(dst, 0)}")
    ins(f"MOVE.L  D1,{opnd(dst, 4)}")


def op(fn, dst, a, b=None):
    """dst = fn(a[, b]) with a basic operation of the runtime"""
    ld(a, 0)
    if b is not None:
        ld(b, 2)
    ins(f"JSR     {fn}")
    if dst:
        st(dst)


def cmp(a, b):
    """D0 = fp_cmp(a, b)"""
    op("fp_cmp", None, a, b)
    ins("TST.L   D0")


def horner(dst, table, n, z):
    ins(f"LEA     rt_math__{table},A0")
    ins(f"MOVEQ   #{n},D0")
    ld(z, 2)
    ins("BSR     rt_math__horner")
    st(dst)


def func(name, slots, doc):
    emit(f"; {doc}")
    emit(f"{name}:")
    ins(f"LINK    A6,#{-8 * slots}")


def ret():
    ins("UNLK    A6")
    ins("RTS")


# ---- header ------------------------------------------------------------------------------------
emit(""";! module    rt_math
;! provides  rt_exp rt_log rt_log10 rt_sin rt_cos rt_tan rt_atn rt_asin rt_acos rt_powf rt_deg rt_rad
;! requires  fp_add fp_sub fp_mul fp_div fp_sqrt fp_cmp fp_int fp_neg fp_to_i32 fp_from_i32 fp_finish rt_error
;! group     float
;! clobbers  D0-D3/A0-A1
;! doc       Transcendental functions, port of runtime/ref/rt_math.c (same operations, same constants).

; GENERATED by tools/gen/gen_rt_math.py from runtime/ref/rt_math.c - do not edit by hand.
; Arguments in D0:D1 (second in D2:D3), result in D0:D1. Temporaries in 8-byte frame slots.
""")

# p = c[0]; p = p*z + c[k]
emit("""; A0 = coefficients (highest first), D0 = count (>= 2), D2:D3 = z -> D0:D1 = polynomial
rt_math__horner:
        MOVEM.L D4-D7/A2,-(SP)
        MOVE.L  A0,A2
        MOVE.L  D0,D7
        MOVE.L  D2,D4
        MOVE.L  D3,D5
        MOVE.L  (A2)+,D0
        MOVE.L  (A2)+,D1
        SUBQ.L  #1,D7
.l:     MOVE.L  D4,D2
        MOVE.L  D5,D3
        JSR     fp_mul
        MOVE.L  (A2)+,D2
        MOVE.L  (A2)+,D3
        JSR     fp_add
        SUBQ.L  #1,D7
        BNE     .l
        MOVEM.L (SP)+,D4-D7/A2
        RTS

; D0:D1 = x, D2 = k -> x * 2^k (overflow: error 1 through fp_finish; tiny: 0)
rt_math__scale:
        MOVE.L  D0,D3                   ; sign in bit 31
        MOVE.L  D0,-(SP)
        OR.L    D1,(SP)+
        BEQ     .zero
        MOVE.L  D2,-(SP)
        MOVE.L  D0,D2                   ; e = biased exponent - 1075 + k
        SWAP    D2
        LSR.W   #4,D2
        AND.L   #$7FF,D2
        SUB.L   #1075,D2
        ADD.L   (SP)+,D2
        AND.L   #$000FFFFF,D0           ; m with the hidden bit
        OR.L    #$00100000,D0
        JMP     fp_finish
.zero:  MOVEQ   #0,D0
        MOVEQ   #0,D1
        RTS
""")

# ---- exp ---------------------------------------------------------------------------------------
func("rt_exp", 4, "D0:D1 = x -> EXP(x)")
st("s1")
cmp("s1", "C_EXP_MAX")
ins("BGT     .ovf")
cmp("s1", "C_EXP_MIN")
ins("BLT     .zero")
op("fp_mul", "s2", "s1", "C_INV_LN2")
op("fp_add", "s2", "s2", "C_HALF")
op("fp_int", "s2", "s2")                       # kf
op("fp_mul", "s3", "s2", "C_LN2_HI")
op("fp_sub", "s3", "s1", "s3")
op("fp_mul", "s4", "s2", "C_LN2_LO")
op("fp_sub", "s3", "s3", "s4")                 # r
horner("s4", "exp_c", 12, "s3")
op("fp_mul", "s4", "s4", "s3")
op("fp_add", "s4", "s4", "C_ONE")
op("fp_mul", "s4", "s4", "s3")
op("fp_add", "s4", "s4", "C_ONE")              # p
ld("s2")
ins("JSR     fp_to_i32")
ins("MOVE.L  D0,D2")
ld("s4")
ins("BSR     rt_math__scale")
ret()
emit(".ovf:   MOVEQ   #1,D0                   ; overflow")
ins("JSR     rt_error")
emit(".zero:  MOVEQ   #0,D0")
ins("MOVEQ   #0,D1")
ret()
emit()

# ---- log ---------------------------------------------------------------------------------------
func("rt_log", 6, "D0:D1 = x -> LOG(x); x <= 0: error 6")
ins("TST.L   D0")
ins("BMI     .err")
ins("MOVE.L  D0,D2                   ; zero (exponent field 0, as in fp_unpack)")
ins("AND.L   #$7FF00000,D2")
ins("BEQ     .err")
ins("MOVE.L  D0,D2                   ; e = biased exponent - 1023")
ins("SWAP    D2")
ins("LSR.W   #4,D2")
ins("AND.L   #$7FF,D2")
ins("SUB.L   #1023,D2")
ins("MOVE.L  D2,-48(A6)              ; slot 6: e (long)")
ins("AND.L   #$000FFFFF,D0           ; m in [1,2)")
ins("OR.L    #$3FF00000,D0")
st("s1")
cmp("s1", "C_SQRT2")
ins("BLE     .m")
ins("SUB.L   #$00100000,-8(A6)       ; m/2, e+1")
ins("ADDQ.L  #1,-48(A6)")
emit(".m:")
op("fp_sub", "s2", "s1", "C_ONE")              # f
op("fp_add", "s3", "C_TWO", "s2")
op("fp_div", "s3", "s2", "s3")                 # s
op("fp_mul", "s4", "s3", "s3")                 # z
horner("s5", "log_c", 11, "s4")
op("fp_mul", "s5", "s5", "s4")                 # R
op("fp_sub", "s5", "s2", "s5")
op("fp_mul", "s5", "s3", "s5")
op("fp_sub", "s5", "s2", "s5")                 # l
ins("MOVE.L  -48(A6),D0")
ins("JSR     fp_from_i32")
st("s4")                                       # ef
op("fp_mul", "s3", "s4", "C_LN2_LO")
op("fp_add", "s3", "s3", "s5")
op("fp_mul", "s4", "s4", "C_LN2_HI")
op("fp_add", None, "s4", "s3")
ret()
emit(".err:   MOVEQ   #6,D0                   ; logarithm only for numbers greater zero")
ins("JSR     rt_error")
ins("MOVEQ   #0,D0")
ins("MOVEQ   #0,D1")
ret()
emit()

emit("rt_log10:")
ins("JSR     rt_log")
ins("MOVE.L  rt_math__c_inv_ln10,D2")
ins("MOVE.L  rt_math__c_inv_ln10+4,D3")
ins("JMP     fp_mul")
emit()

# ---- reduction and kernels -----------------------------------------------------------------------
func("rt_math__red", 4, "D0:D1 = x -> D0:D1 = r, D2 = n mod 4 (x = n pi/2 + r); passes of 26 bits of n")
ins("CLR.L   -32(A6)                 ; slot 4: quadrant (long)")
st("s1")
emit(".pass:")
ld("s1")
ins("AND.L   #$7FFFFFFF,D0")
ld("C_PIO4", 2)
ins("JSR     fp_cmp")
ins("TST.L   D0")
ins("BLE     .done")
op("fp_mul", "s2", "s1", "C_TWO_OVER_PI")
op("fp_add", "s2", "s2", "C_HALF")
ld("s2")
ins("JSR     fp_int")
ins("AND.L   #$F8000000,D1           ; the top 26 bits of n")
st("s2")
op("fp_mul", "s3", "s2", "C_QUARTER")
op("fp_int", "s3", "s3")
op("fp_mul", "s3", "s3", "C_FOUR")
op("fp_sub", "s3", "s2", "s3")
ins("JSR     fp_to_i32")
ins("ADD.L   D0,-32(A6)")
for part in ("C_PIO2_1", "C_PIO2_2", "C_PIO2_3", "C_PIO2_4"):
    op("fp_mul", "s3", "s2", part)
    op("fp_sub", "s1", "s1", "s3")
ins("BRA     .pass")
emit(".done:")
ld("s1")
ins("MOVE.L  -32(A6),D2")
ins("AND.L   #3,D2")
ret()
emit()

func("rt_math__ksin", 3, "D0:D1 = r -> sin(r) for |r| <= pi/4")
st("s1")
op("fp_mul", "s2", "s1", "s1")                 # z
horner("s3", "sin_c", 8, "s2")
op("fp_mul", "s2", "s1", "s2")
op("fp_mul", "s2", "s2", "s3")
op("fp_add", None, "s1", "s2")
ret()
emit()

func("rt_math__kcos", 2, "D0:D1 = r -> cos(r) for |r| <= pi/4")
st("s1")
op("fp_mul", "s1", "s1", "s1")                 # z
horner("s2", "cos_c", 8, "s1")
op("fp_mul", "s2", "s1", "s2")
op("fp_add", None, "C_ONE", "s2")
ret()
emit()

for fname, table in (("rt_sin", ("ksin", "kcos", "-ksin", "-kcos")), ("rt_cos", ("kcos", "-ksin", "-kcos", "ksin"))):
    emit(f"; D0:D1 = x -> {fname[3:].upper()}(x)")
    emit(f"{fname}:")
    ins("BSR     rt_math__red")
    for q, k in enumerate(table):
        if q < 3:
            ins(f"CMP.L   #{q},D2")
            ins(f"BEQ     .q{q}")
    emit(".q3:")
    for q, k in [(3, table[3]), (0, table[0]), (1, table[1]), (2, table[2])]:
        if q != 3:
            emit(f".q{q}:")
        if k.startswith("-"):
            ins(f"BSR     rt_math__{k[1:]}")
            ins("JMP     fp_neg")
        else:
            ins(f"BRA     rt_math__{k}")
    emit()

func("rt_tan", 3, "D0:D1 = x -> TAN(x)")
ins("BSR     rt_math__red")
st("s1")
ins("MOVE.L  D2,-24(A6)              ; slot 3: quadrant")
ins("BSR     rt_math__ksin")
st("s2")
ld("s1")
ins("BSR     rt_math__kcos")
st("s1")                                       # c
ins("BTST    #0,-21(A6)")
ins("BNE     .odd")
op("fp_div", None, "s2", "s1")
ret()
emit(".odd:")
op("fp_div", None, "s1", "s2")
ins("JSR     fp_neg")
ret()
emit()

# ---- atn, asin, acos ------------------------------------------------------------------------------
func("rt_atn", 4, "D0:D1 = x -> ATN(x)")
ins("CLR.L   -32(A6)                 ; slot 4: flags (bit 0 negative, 1 inverse, 2 pi/6)")
ins("TST.L   D0")
ins("BPL     .p")
ins("BSET    #0,-29(A6)")
emit(".p:")
ins("AND.L   #$7FFFFFFF,D0")
st("s1")                                       # t
cmp("s1", "C_ONE")
ins("BLE     .le1")
op("fp_div", "s1", "C_ONE", "s1")
ins("BSET    #1,-29(A6)")
emit(".le1:")
cmp("s1", "C_TAN_PI12")
ins("BLE     .small")
op("fp_mul", "s2", "s1", "C_SQRT3")
op("fp_sub", "s2", "s2", "C_ONE")
op("fp_add", "s3", "s1", "C_SQRT3")
op("fp_div", "s1", "s2", "s3")
ins("BSET    #2,-29(A6)")
emit(".small:")
op("fp_mul", "s2", "s1", "s1")                 # z
horner("s3", "atn_c", 14, "s2")
op("fp_mul", "s2", "s1", "s2")
op("fp_mul", "s2", "s2", "s3")
op("fp_add", "s1", "s1", "s2")                 # a
ins("BTST    #2,-29(A6)")
ins("BEQ     .n6")
op("fp_add", "s1", "C_PIO6", "s1")
emit(".n6:")
ins("BTST    #1,-29(A6)")
ins("BEQ     .ni")
op("fp_sub", "s1", "C_PIO2", "s1")
emit(".ni:")
ld("s1")
ins("BTST    #0,-29(A6)")
ins("BEQ     .out")
ins("JSR     fp_neg")
emit(".out:")
ret()
emit()

func("rt_asin", 2, "D0:D1 = x -> ASIN(x); |x| > 1: error 67")
st("s1")
ins("AND.L   #$7FFFFFFF,D0")
ld("C_ONE", 2)
ins("JSR     fp_cmp")
ins("TST.L   D0")
ins("BGT     .err")
ins("BLT     .in")
ld("C_PIO2")
ins("TST.L   -8(A6)")
ins("BPL     .out")
ins("JSR     fp_neg")
emit(".out:")
ret()
emit(".in:")
op("fp_sub", "s2", "C_ONE", "s1")
ld("C_ONE")
ld("s1", 2)
ins("JSR     fp_add")
ld("s2", 2)
ins("JSR     fp_mul")
ins("JSR     fp_sqrt")
ins("MOVE.L  D0,D2")
ins("MOVE.L  D1,D3")
ld("s1")
ins("JSR     fp_div")
ins("BSR     rt_atn")
ret()
emit(".err:   MOVEQ   #67,D0                  ; asin/acos error")
ins("JSR     rt_error")
ins("MOVEQ   #0,D0")
ins("MOVEQ   #0,D1")
ret()
emit()

func("rt_acos", 2, "D0:D1 = x -> ACOS(x); |x| > 1: error 67")
st("s1")
ins("AND.L   #$7FFFFFFF,D0")
st("s2")                                       # a = |x|
cmp("s2", "C_ONE")
ins("BGT     .err")
cmp("s2", "C_HALF")
ins("BGT     .half")
ld("s1")
ins("BSR     rt_asin")
ins("MOVE.L  D0,D2")
ins("MOVE.L  D1,D3")
ld("C_PIO2")
ins("JSR     fp_sub")
ret()
emit(".half:")
op("fp_sub", "s2", "C_ONE", "s2")
op("fp_mul", "s2", "s2", "C_HALF")
ins("JSR     fp_sqrt")
ins("BSR     rt_asin")
ld("C_TWO", 2)
ins("JSR     fp_mul")
ins("TST.L   -8(A6)")
ins("BPL     .out")
ins("MOVE.L  D0,D2")
ins("MOVE.L  D1,D3")
ld("C_PI")
ins("JSR     fp_sub")
emit(".out:")
ret()
emit(".err:   MOVEQ   #67,D0                  ; asin/acos error")
ins("JSR     rt_error")
ins("MOVEQ   #0,D0")
ins("MOVEQ   #0,D1")
ret()
emit()

# ---- pow, deg, rad -------------------------------------------------------------------------------
func("rt_powf", 1, "D0:D1 = x, D2:D3 = y (not an integer) -> x^y = EXP(y*LOG(x)); 0^y: 0, y < 0 error 0")
st("s1")
ins("AND.L   #$7FF00000,D0           ; x zero (exponent field 0)?")
ins("BNE     .nz")
ins("MOVE.L  D2,D0                   ; y < 0 (not zero): divide by zero")
ins("AND.L   #$7FF00000,D0")
ins("BEQ     .zero")
ins("TST.L   D2")
ins("BPL     .zero")
ins("MOVEQ   #0,D0                   ; divide by zero")
ins("JSR     rt_error")
emit(".zero:  MOVEQ   #0,D0")
ins("MOVEQ   #0,D1")
ret()
emit(".nz:    MOVEM.L D2-D3,-(SP)")
ld("s1")
ins("JSR     rt_log")
ins("MOVEM.L (SP)+,D2-D3")
ins("EXG     D0,D2")
ins("EXG     D1,D3")
ins("JSR     fp_mul")
ins("BSR     rt_exp")
ret()
emit()

emit("; D0:D1 = x -> DEG(x) = x*180/PI")
emit("rt_deg:")
ld("C_D180", 2)
ins("JSR     fp_mul")
ld("C_PI", 2)
ins("JMP     fp_div")
emit()
emit("; D0:D1 = x -> RAD(x) = x*PI/180")
emit("rt_rad:")
ld("C_PI", 2)
ins("JSR     fp_mul")
ld("C_D180", 2)
ins("JMP     fp_div")
emit()

# ---- constants -----------------------------------------------------------------------------------
emit(";! section data")
consts["C_ONE"] = "0x3FF0000000000000"
for name, val in sorted(consts.items()):
    v = int(val, 16)
    emit(f"rt_math__{name.lower()}:")
    ins(f"DC.L    ${v >> 32:08X},${v & 0xFFFFFFFF:08X}")
for name, vals in tables.items():
    emit(f"rt_math__{name}:")
    for val in vals:
        v = int(val[:-1], 16)
        ins(f"DC.L    ${v >> 32:08X},${v & 0xFFFFFFFF:08X}")

(ROOT / "runtime/m68k/rt_math.s").write_text("\n".join(out) + "\n")
